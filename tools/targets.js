// Targets reader: the latest value of each target in docs/bench/targets.jsonl, with its residual and its last five measured values;
// rewrites docs/bench/targets.md (a table, as budget.md is generated). Prints the table; never fails for a target out.
// Usage: node tools/targets.js [--name PATTERN] [--since DATE] [--file FILE] [--md FILE] [--no-md]
//   --name PATTERN  only targets whose name matches PATTERN (a regular expression)
//   --since DATE    only records from DATE (YYYY-MM-DD) on
//   --file FILE     the records to read (default docs/bench/targets.jsonl)
//   --md FILE       the table to write (default docs/bench/targets.md); --no-md writes none
// Records are appended by `--record` on the checks that are targets (tests/lib/targets.js) and by the nightly.
require('./help.js')(__filename);
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..'), args = process.argv.slice(2);
const opt = (k, d) => { const i = args.indexOf(k); return i < 0 ? d : args[i + 1]; };
const src = opt('--file', path.join(root, 'docs/bench/targets.jsonl')), md = args.includes('--no-md') ? null : opt('--md', path.join(root, 'docs/bench/targets.md'));
const pattern = new RegExp(opt('--name', '')), since = opt('--since', '');
const recs = (fs.existsSync(src) ? fs.readFileSync(src, 'utf8') : '').split('\n').filter(Boolean)
  .map((l) => { try { return JSON.parse(l); } catch (e) { return null; } })
  .filter((r) => r && pattern.test(r.name) && (r.date || '') >= since);
const by = new Map();
for (const r of recs) (by.get(r.name) || by.set(r.name, []).get(r.name)).push(r);
const goal = (r) => (Array.isArray(r.target) ? r.target.join('..') : r.target) + (r.unit || '');
const rows = [...by.entries()].sort((a, b) => a[0].localeCompare(b[0])).map(([name, rs]) => {
  const last = rs[rs.length - 1];
  return { name, where: last.where || '', measured: last.measured + (last.unit || ''), target: goal(last), residual: (last.residual > 0 ? '+' : '') + last.residual,
    status: last.status, date: (last.date || '').slice(0, 10), commit: String(last.commit || '').slice(0, 7), lastFive: rs.slice(-5).map((r) => r.measured).join(', ') };
});
const out = rows.filter((r) => r.status === 'out').length, noise = rows.filter((r) => r.status === 'noise').length;
const table = ['| Target | Where | Measured | Target | Residual | Status | Date | Commit | Last five |', '|---|---|---|---|---|---|---|---|---|',
  ...rows.map((r) => `| ${r.name} | ${r.where} | ${r.measured} | ${r.target} | ${r.residual} | ${r.status} | ${r.date} | ${r.commit} | ${r.lastFive} |`)];
const summary = `${rows.length} targets: ${rows.length - out - noise} in, ${out} out, ${noise} within noise`;
console.log(table.join('\n') + '\n\n' + summary);
if (md) {
  fs.mkdirSync(path.dirname(md), { recursive: true });
  fs.writeFileSync(md, '# Targets\n\nGenerated by `node tools/targets.js` from `targets.jsonl`; do not edit. Residual: positive is worse.\n\n' +
    (rows.length ? table.join('\n') : '(no records yet)') + '\n\n' + summary + '\n');
}
